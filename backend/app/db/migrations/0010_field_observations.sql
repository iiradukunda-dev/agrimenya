-- Farmer-submitted observations stay in field_reports and never enter NISR imports.
alter table field_reports
    add column if not exists observed_on date,
    add column if not exists reporter_id uuid references community_accounts(id) on delete set null,
    add column if not exists photo_path text;

update field_reports set observed_on = submitted_at::date where observed_on is null;
alter table field_reports alter column observed_on set default current_date;
alter table field_reports alter column observed_on set not null;

create index if not exists field_reports_observed_on_idx
    on field_reports(observed_on desc);
create index if not exists field_reports_reporter_idx
    on field_reports(reporter_id, submitted_at desc);

comment on table field_reports is 'Farmer/field observations; not official NISR data and never used as NISR yield baselines.';
comment on column field_reports.photo_path is 'Private Supabase Storage object path; issue short-lived signed URLs when needed.';

-- Private bucket: photos are exposed to authenticated community members only via
-- short-lived signed URLs generated by the API.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('community-field-reports', 'community-field-reports', false, 5242880, array['image/jpeg'])
on conflict (id) do nothing;
